// ---- Side and axle: set by the seller, or read from the title ("левая", "передний") ----
export type Side = 'left' | 'right';
export type Axle = 'front' | 'rear';
const low = (s?: string) => String(s || '').toLowerCase().replace(/ё/g, 'е');

export function partSide(p: Pick<AutoPartItem, 'title'> & { side?: Side }): Side | null {
  if (p.side === 'left' || p.side === 'right') return p.side;
  const t = low(p.title);
  if (/(^|[^а-я])(лев(ая|ый|ое|ые|ой|ую)|лев\.?|lh)([^а-я]|$)/.test(t)) return 'left';
  if (/(^|[^а-я])(прав(ая|ый|ое|ые|ой|ую)|прав\.?|rh)([^а-я]|$)/.test(t)) return 'right';
  return null;
}
export function partAxle(p: Pick<AutoPartItem, 'title'> & { axle?: Axle }): Axle | null {
  if (p.axle === 'front' || p.axle === 'rear') return p.axle;
  const t = low(p.title);
  if (/(^|[^а-я])(передн(яя|ий|ее|ие|ей|юю)|перед\.?|fr)([^а-я]|$)/.test(t)) return 'front';
  if (/(^|[^а-я])(задн(яя|ий|ее|ие|ей|юю)|зад\.?|rr)([^а-я]|$)/.test(t)) return 'rear';
  return null;
}
export const SIDE_LABEL: Record<Side, string> = { left: 'Левая', right: 'Правая' };
export const AXLE_LABEL: Record<Axle, string> = { front: 'Передняя', rear: 'Задняя' };

