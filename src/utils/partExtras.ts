export function relatedQueries(p: Pick<AutoPartItem, 'title'>): string[] {
  const t = low(p.title);
  for (const [re, list] of RELATED) if (re.test(t)) return list.filter((q) => !t.includes(q.split(' ')[0]));
  return [];
}

// ---- Private notes on listings (only in this browser) ----
const NOTES_KEY = 'kgzone-part-notes';
let notes: Record<string, string> = (() => { try { return JSON.parse(localStorage.getItem(NOTES_KEY) || '{}'); } catch { return {}; } })();
const noteListeners = new Set<() => void>();
export function setPartNote(id: string, text: string) {
  const next = { ...notes };
  if (text.trim()) next[id] = text.slice(0, 500); else delete next[id];
  notes = next;
  try { localStorage.setItem(NOTES_KEY, JSON.stringify(notes)); } catch { /* storage unavailable */ }
  noteListeners.forEach((l) => l());
}
export const usePartNotes = () => useSyncExternalStore((l) => { noteListeners.add(l); return () => noteListeners.delete(l); }, () => notes, () => notes);
